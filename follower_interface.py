def crc16_modbus(data: bytes) -> int:
    crc_hi = 0xFF
    crc_lo = 0xFF
    for byte in data:
        index = crc_hi ^ byte
        # Match follower firmware's current CRC routine/table usage.
        crc_hi = crc_lo ^ int(_AUCH_CRCLo[index])
        crc_lo = int(_AUCH_CRCHI[index])
    return (crc_hi << 8) | crc_lo


def _parse_feedback_payload(payload: bytes) -> np.ndarray:
    if len(payload) != DLC_FEEDBACK:
        raise ValueError("feedback payload must be 14 bytes")
    values = np.empty(7, dtype=np.float32)
    for idx in range(6):
        raw = int.from_bytes(payload[idx * 2 : idx * 2 + 2], "big", signed=True)
        values[idx] = raw / 10.0
    gripper_raw = int.from_bytes(payload[12:14], "big", signed=False)
    values[6] = (gripper_raw * 100.0) / 65535.0
    return values


class FollowerArmController(ABC):
    """Base interface for a follower arm controller."""

    def __init__(self):
        self.last_valid_state: np.ndarray | None = None

    @abstractmethod
    def read_state(self) -> np.ndarray:
        """Read the current follower state."""

    @abstractmethod
    def send_action(self, action: np.ndarray):
        """Send an action command to the follower arm."""

    def close(self):
        pass


class SerialFollowerArmController(FollowerArmController):
    def __init__(self, port: str, baudrate: int = 76800, timeout: float = 0.0, tx_hz: float = 30.0):
        super().__init__()
        try:
            ser = serial.Serial()
            ser.port = port
            ser.baudrate = baudrate
            ser.timeout = timeout
            # Some USB-serial adapters raise OSError on DTR/RTS ioctl — swallow it.
            for _attr in ("_update_dtr_state", "_update_rts_state"):
                _orig = getattr(ser, _attr)
                def _safe(_orig=_orig):
                    try:
                        _orig()
                    except OSError:
                        pass
                setattr(ser, _attr, _safe)
            ser.open()
            self.ser = ser
            print(f"[HW] 폴로어암 시리얼 연결 성공 ({port})")
        except serial.SerialException as e:
            print(f"[에러] 폴로어암 시리얼 포트를 열 수 없습니다: {e}")
            self.ser = None
        self._rx_buffer = bytearray()
        self._tx_period = 0.0 if tx_hz <= 0 else 1.0 / tx_hz
        self._next_tx_time = 0.0

    @property
    def is_connected(self) -> bool:
        return self.ser is not None and self.ser.is_open

    def _try_parse_feedback(self) -> tuple[np.ndarray, bool] | tuple[None, bool]:
        buffer = self._rx_buffer
        while len(buffer) >= FRAME_LEN_FEEDBACK:
            start_idx = buffer.find(START_BYTES)
            if start_idx == -1:
                buffer.clear()
                return None, False
            if start_idx > 0:
                del buffer[:start_idx]
                continue
            if len(buffer) < FRAME_LEN_FEEDBACK:
                return None, False
            frame = bytes(buffer[:FRAME_LEN_FEEDBACK])
            if frame[4] != CMD_FEEDBACK or frame[5] != DLC_FEEDBACK:
                del buffer[0]
                continue
            payload = frame[6:6 + DLC_FEEDBACK]
            crc_received = int.from_bytes(frame[20:22], "big")
            crc_calculated = crc16_modbus(frame[:20])
            if crc_received != crc_calculated:
                del buffer[0]
                continue
            del buffer[:FRAME_LEN_FEEDBACK]
            return _parse_feedback_payload(payload), True
        return None, False

    def read_state_sample(self) -> tuple[np.ndarray, bool]:
        """Return the newest follower feedback state sample."""
        if not self.is_connected:
            raise RuntimeError("Follower arm is not connected.")

        try:
            available = self.ser.in_waiting
            if available:
                self._rx_buffer.extend(self.ser.read(available))
            parsed, ok = self._try_parse_feedback()
            if ok and parsed is not None:
                self.last_valid_state = parsed
                return parsed.copy(), True
            if self.last_valid_state is None:
                return np.zeros(7, dtype=np.float32), False
            return self.last_valid_state.copy(), False
        except serial.SerialException:
            if self.last_valid_state is None:
                return np.zeros(7, dtype=np.float32), False
            return self.last_valid_state.copy(), False

    def read_state(self) -> np.ndarray:
        return self.read_state_sample()[0]

    def send_action(self, action: np.ndarray):
        if not self.is_connected:
            return

        if self._tx_period > 0.0:
            now = time.perf_counter()
            if now < self._next_tx_time:
                return
            # Keep a stable cadence while recovering gracefully from delays.
            self._next_tx_time = max(self._next_tx_time + self._tx_period, now + self._tx_period)

        if action.shape != (7,):
            raise ValueError("action must be a 7-dimensional numpy array")

        # Follower firmware expects actuator commands in 1e-4 deg units.
        pos_raw = np.rint(np.asarray(action[:6], dtype=np.float64) * 10000.0).astype(np.int64, copy=False)

        # Follower firmware expects gripper in [0, 1] mapped to uint16.
        gripper_norm = float(np.clip(action[6], 0.0, 100.0) / 100.0)
        gripper_raw = int(np.round(gripper_norm * 65535.0))
        frame = bytearray(START_BYTES)
        frame.append(CMD_POSREF)
        frame.append(DLC_POSREF)
        for value in pos_raw:
            clipped = int(np.clip(value, np.iinfo(np.int32).min, np.iinfo(np.int32).max))
            frame.extend(clipped.to_bytes(4, "big", signed=True))
        gripper_clipped = int(np.clip(gripper_raw, 0, np.iinfo(np.uint16).max))
        frame.extend(gripper_clipped.to_bytes(2, "big", signed=False))
        crc = crc16_modbus(bytes(frame))
        frame.extend(crc.to_bytes(2, "big"))

        try:
            self.ser.write(frame)
        except serial.SerialException as e:
            print(f"[경고] 팔로어암 명령 전송 실패: {e}")

    def close(self):
        if self.ser and self.ser.is_open:
            self.ser.close()
            print("[HW] 팔로어암 시리얼 연결 종료")
